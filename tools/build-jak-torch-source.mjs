import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';

const catalogue=JSON.parse(await readFile(new URL('../public/jak-lab/catalogue.json',import.meta.url),'utf8'));
const source=catalogue.groups.find(group=>group.name==='group-part-maincave-torch');
assert.ok(source,'Missing published Jak torch source');
const group=Object.fromEntries(['id','name','source','items','bounds','duration','linger-duration'].map(key=>[key,source[key]]));
const definitions=new Map(catalogue.particles.map(p=>[p.id,p])),ids=new Set();
function visit(id){
  if(ids.has(id))return;ids.add(id);
  const part=definitions.get(id);assert.ok(part,`Missing torch launcher ${id}`);
  for(const field of part.fields)if(field.field==='next-launcher')visit(field.base);
}
group.items.forEach(item=>visit(item.particle));
const particles=[...ids].sort((a,b)=>a-b).map(id=>{
  const {source,fields}=definitions.get(id);return {id,source,fields};
});
const output=`// Generated by tools/build-jak-torch-source.mjs from the published Jak catalogue.\n`+
  `// Original launcher graph, 300 Hz units and colour/lifetime fields; no art download.\n`+
  `import type {EffectDefinition,ParticleDefinition} from './jak-lab/types';\n`+
  `export const JAK_TORCH_GROUP:EffectDefinition=${JSON.stringify(group)};\n`+
  `export const JAK_TORCH_PARTICLES:ParticleDefinition[]=${JSON.stringify(particles)};\n`;
const path=new URL('../src/jakTorchSource.generated.ts',import.meta.url);
if(process.argv.includes('--write'))await writeFile(path,output);
else assert.equal(await readFile(path,'utf8'),output,'Torch source drifted from the ported catalogue');
console.log(`PASS Jak torch source: group ${group.id}, ${particles.length} original launchers`);
