import {createRequire} from 'node:module';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import path from 'node:path';

const {chromium}=createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE||'playwright');
const source=process.argv[2]??'tools/rally-sponsors/sources';
const out=process.argv[3]??'public/rally';
const names=['pisupo-petes','crusty-creme','trashed','milk','uga-beach','fleshy-freds','bones','coconut-cart-rally'];
const inputs=[];
for(const name of names){
 const bytes=await readFile(path.join(source,name+'.png'));
 inputs.push({name,sha256:createHash('sha256').update(bytes).digest('hex'),data:'data:image/png;base64,'+bytes.toString('base64')});
}
const browser=await chromium.launch({channel:'chrome',headless:true});
try{
 const page=await browser.newPage();
 const result=await page.evaluate(async inputs=>{
  const width=1024,rowHeight=256,height=rowHeight*inputs.length;
  const canvas=document.createElement('canvas');canvas.width=width;canvas.height=height;
  const c=canvas.getContext('2d'),entries=[];
  for(const [i,input]of inputs.entries()){
   const image=new Image();image.src=input.data;await image.decode();
   // Retain the atlas packing scale. Geometry crops these rows and uses
   // the original aspect ratio for both stadium artwork and kart decals.
   const h=Math.min(240,image.height),w=image.width/image.height*h*(4/(20/4.45));
   const x=(width-w)/2,y=i*rowHeight+(rowHeight-h)/2;
   c.drawImage(image,x,y,w,h);
   entries.push({name:input.name,sha256:input.sha256,sourceSize:[image.width,image.height],aspect:image.width/image.height,uv:[x/width,1-(y+h)/height,(x+w)/width,1-y/height]});
  }
  return {width,height,rows:inputs.length,webp:canvas.toDataURL('image/webp',.94),png:canvas.toDataURL('image/png'),entries};
 },inputs);
 const bytes=Buffer.from(result.webp.split(',')[1],'base64');
 await mkdir(out,{recursive:true});await writeFile(path.join(out,'sponsors-v3.webp'),bytes);
 const metadata={width:result.width,height:result.height,rows:result.rows,entries:result.entries};
 await writeFile('tools/rally-sponsors/atlas.json',JSON.stringify(metadata,null,2)+'\n');
 const art=result.entries.map(({name,aspect,uv})=>({name,aspect,uv}));
 await writeFile('src/rallySponsors.ts','/** Supplied artwork, packed once for stadium ads and cutout kart decals. Generated by tools/build-rally-sponsors.mjs. */\nexport const RALLY_SPONSORS='+JSON.stringify(art,null,2)+' as const;\n');
 if(process.env.SPONSOR_PREVIEW)await writeFile(process.env.SPONSOR_PREVIEW,Buffer.from(result.png.split(',')[1],'base64'));
 console.log(JSON.stringify({file:path.join(out,'sponsors-v3.webp'),bytes:bytes.length,...metadata}));
}finally{await browser.close();}
