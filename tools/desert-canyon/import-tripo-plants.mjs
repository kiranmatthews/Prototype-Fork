// Preserve the original Smart Mesh export byte-for-byte, including its atlas.
import assert from 'node:assert/strict';
import {readFile,writeFile,copyFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {homedir} from 'node:os';
import {join} from 'node:path';
import {measureGlb} from '../ancient-gates-tripo/ancient-native-measure.mjs';
const sources=JSON.parse(await readFile('tools/desert-canyon/tripo-plants.json','utf8'));
const directory=process.argv[2]??join(homedir(),'Downloads');
const assets=[];
for(const source of sources.assets){
  assert.ok(source.taskId,'Missing Tripo provenance');
  const input=join(directory,`canyon-${source.id}-smart.glb`),bytes=await readFile(input),native=await measureGlb(input);
  assert.ok(native.triangles>0&&native.triangles<=30000,`${source.id} exceeds the hard 30k budget`);
  // Smart Mesh targets can overshoot slightly. Record both target and actual;
  // preserve the completed native geometry rather than quietly decimating it.
  assert.ok(native.triangles<=source.requestedTriangles*1.1,`${source.id} exceeds its practical authoring budget`);
  assert.equal(native.materials,1,'The instance renderer requires one atlas material');
  const json=JSON.parse(bytes.subarray(20,20+bytes.readUInt32LE(12)));
  assert.ok(json.materials[0].pbrMetallicRoughness.baseColorTexture,'Missing generated colour atlas');
  assert.ok(json.meshes.every(m=>m.primitives.every(p=>p.attributes.NORMAL!==undefined&&p.attributes.TEXCOORD_0!==undefined)));
  assert.ok(!json.nodes.some(n=>/_LOD[1-9]/.test(n.name??'')),'No distance variants');
  const file=source.id+'.glb';await copyFile(input,'public/desert-canyon/plants/'+file);
  assets.push({...source,file,triangles:native.triangles,vertices:native.vertices,size:native.size,bytes:bytes.length,
    sha256:createHash('sha256').update(bytes).digest('hex'),reference:'../../../tools/desert-canyon/plant-references/'+source.id+'.png',
    textureResolution:2048,credits:{smartMesh:100,texture:10},nativeExportPreserved:true});
}
const manifest={method:'Tripo web app in Chrome, Smart Mesh P2.0 Triangle and 2K reference texture; plan credits',
  geometryPolicy:'Byte-exact original GLB; complete authored geometry at all distances and in reflections',assets};
await writeFile('public/desert-canyon/plants/manifest.json',JSON.stringify(manifest,null,2)+'\n');
const catalog=Object.fromEntries(assets.map(a=>[a.kind,{file:'../desert-canyon/plants/'+a.id,label:'Bryce · cartoon '+a.id,
  size:a.size,wind:false,normalStrength:0,roughness:.94,doubleSided:true,cellSize:72}]));
await writeFile('src/desertPlantCatalog.ts','// Generated by tools/desert-canyon/import-tripo-plants.mjs. Original Smart Mesh geometry.\nexport const DESERT_PLANT_ASSETS='+JSON.stringify(catalog,null,2)+' as const;\n');
console.log(JSON.stringify(assets.map(({id,triangles,bytes})=>({id,triangles,bytes})),null,2));
