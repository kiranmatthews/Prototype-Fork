"""Bake the complete triple-nozzle Meshy surface for shared kart instancing.
Run with Blender --background --python tools/golf-cart/flame-nozzle/bake.py.
No decimation, silhouette substitute, external URL or runtime credential.
"""
import base64,hashlib,json
from pathlib import Path
import bpy
import numpy as np
ROOT=Path(__file__).resolve().parents[3]
HERE=Path(__file__).resolve().parent
source=ROOT/'.img2threejs/flame-nozzle/triple-nozzle.glb'
bpy.ops.wm.read_factory_settings(use_empty=True)
bpy.ops.import_scene.gltf(filepath=str(source))
objects=[o for o in bpy.context.scene.objects if o.type=='MESH']
assert len(objects)==1,'Review multipart Meshy output before baking'
obj=objects[0];mesh=obj.data;mesh.calc_loop_triangles()
raw=np.array([tuple(obj.matrix_world@v.co) for v in mesh.vertices])
# Blender Z-up -> Three Y-up. Canonical module openings face +Z.
position=raw[:,[0,2,1]]*np.array([1,1,-1])
low=position.min(axis=0);high=position.max(axis=0)
scale=.40/(high[0]-low[0]);position=(position-(low+high)/2)*scale
assert np.ptp(position[:,1]) < .28 and np.ptp(position[:,2]) < .35,'Review model orientation/proportions'
# Keep source normals and all UV seams; every original triangle survives.
normal_matrix=obj.matrix_world.to_3x3().inverted().transposed()
normals=np.array([tuple(normal_matrix@v.normal) for v in mesh.vertices])[:,[0,2,1]]*np.array([1,1,-1])
normals/=np.maximum(1e-12,np.linalg.norm(normals,axis=1)[:,None])
material=mesh.materials[0]
bsdf=next(n for n in material.node_tree.nodes if n.type=='BSDF_PRINCIPLED')
image=bsdf.inputs['Base Color'].links[0].from_node.image
image.scale(256,256)
pixels=np.clip(np.array(image.pixels[:]).reshape(256,256,4),0,1)[::-1].copy();pixels[:,:,3]=1
uv_layer=mesh.uv_layers.active.data
vertices={};points=[];normal_out=[];uvs=[];indices=[]
for tri in mesh.loop_triangles:
 for vi,li in zip(tri.vertices,tri.loops):
  u,v=uv_layer[li].uv;v=1-v;key=(int(vi),round(float(u),7),round(float(v),7))
  if key not in vertices:
   vertices[key]=len(points);points.append(position[vi]);normal_out.append(normals[vi]);uvs.append([u,v])
  indices.append(vertices[key])
assert len(indices)==len(mesh.loop_triangles)*3 and len(points)<65536
pack=lambda a,t:base64.b64encode(np.asarray(a,dtype=t).tobytes()).decode()
data={'position':pack(points,'<f4'),'normal':pack(normal_out,'<f4'),'uv':pack(uvs,'<f4'),'indices':{'main':pack(indices,'<u2')},'pixels':pack(np.round(pixels*255),'uint8'),'textureSize':256}
(ROOT/'src/golf-cart/flameNozzle-data.ts').write_text('// Complete Meshy triple-nozzle surface. Generated by tools/golf-cart/flame-nozzle/bake.py.\nexport const FLAME_NOZZLE_DATA = '+json.dumps(data,separators=(',',':'))+' as const;\n')
ledger=json.loads((HERE/'tasks.json').read_text())
report={'sourceTask':ledger['tasks']['triple-nozzle']['id'],'sourceSha256':hashlib.sha256(source.read_bytes()).hexdigest(),'triangles':len(indices)//3,'vertices':len(points),'fullNativeGeometry':True,'bounds':{'min':position.min(axis=0).tolist(),'max':position.max(axis=0).tolist()},'textureSize':256,'front':'+Z'}
(HERE/'provenance.json').write_text(json.dumps(report,indent=2)+'\n');print(json.dumps(report))
