import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const modules = new Map();
for (const name of ['settings','controls','optimize']) {
  const source = await readFile(new URL(`../src/crt-guest/${name}.ts`,import.meta.url),'utf8');
  const output = ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
  const module = {exports:{}};
  new Function('require','module','exports',output)(name=>modules.get(name.replace('./','')),module,module.exports);
  modules.set(name,module.exports);
}
const {CrtGuestSettings}=modules.get('settings');
const {planCrt}=modules.get('optimize');
const {crtHalfFloat,crtFrameMetadata,optimizeNativeVertical}=modules.get('optimize');
const {crtRadiusMaximum,isCrtControlRelevant:visible,setCrtControlSourceHeight,subscribeCrtControlContext}=modules.get('controls');
const settings=new CrtGuestSettings({storage:null,loadStored:false,persistChanges:false});
const v=(id,value)=>settings.setValue(id,value);
assert.deepEqual(planCrt(settings,1080),{afterglow:true,average:false,edges:false,glow:false,bloom:false,fusePre:true,fuseInput:false,reconstruction:true,mipmaps:false,scalarAverage:false});
assert.equal(planCrt(settings,1080,1920,1920).reconstruction,false);
assert.equal(planCrt(settings,360,640,1920).reconstruction,true);
assert.equal(visible('esrc',settings),false);assert.equal(visible('LS',settings),false);
v('AS',0);assert.equal(planCrt(settings,1080).fuseInput,true);
v('BP',1);assert.equal(planCrt(settings,1080).afterglow,false,'Threshold-only black lift is computed from stock without a history pass');
v('BP',-5);assert.equal(planCrt(settings,1080).afterglow,false);
v('glow',.3);assert.equal(planCrt(settings,1080).glow,true);assert.equal(planCrt(settings,1080).bloom,false);
v('m_glow',2);assert.equal(planCrt(settings,1080).bloom,false,'Magic glow derives its local Bloom from Glow, not BloomPass');
assert.equal(visible('m_glow_cutoff',settings),true);assert.equal(visible('SIGMA_HB',settings),false);
v('halation',-.5);assert.equal(planCrt(settings,1080).bloom,true);assert.equal(visible('SIGMA_HB',settings),true);
v('halation',0);v('mask_bloom',1);v('shadowMask',-1);assert.equal(planCrt(settings,1080).bloom,false);
v('shadowMask',6);assert.equal(planCrt(settings,1080).bloom,true);
let notifications=0;const stop=subscribeCrtControlContext(settings,()=>notifications++);
setCrtControlSourceHeight(settings,360);assert.equal(visible('beam_min',settings),true);assert.equal(visible('SIGMA_VER',settings),false);
setCrtControlSourceHeight(settings,1080);assert.equal(visible('beam_min',settings),false);assert.equal(visible('SIGMA_VER',settings),true);
setCrtControlSourceHeight(settings,1080);assert.equal(notifications,2);stop();
assert.equal(visible('auto_res',settings),false);
assert.equal(visible('scangamma',settings),true,'Peak gamma still affects masks without progressive scanlines');
setCrtControlSourceHeight(settings,360,640);assert.equal(visible('auto_res',settings),true);
v('SIZEH',50);v('SIGMA_H',1.2);assert.equal(crtRadiusMaximum('SIZEH',settings),8);
assert.equal(settings.getValue('SIZEH'),50,'Effective UI range must not rewrite imported radii');
v('SIGMA_H',15);assert.equal(crtRadiusMaximum('SIZEH',settings),50);
v('interm',1);assert.equal(planCrt(settings,1080).fusePre,false,'Two-line temporal reconstruction keeps the pre image');
v('interm',0);assert.equal(visible('beam_min',settings),true);assert.equal(planCrt(settings,1080).fusePre,true);
v('vigstr',.5);assert.equal(planCrt(settings,1080).fusePre,false,'Vignette alpha must survive pre-image filtering');
settings.setVariant('advanced');v('BLOOM',1);v('smart_ei',0);
assert.equal(planCrt(settings,360).scalarAverage,true);assert.equal(planCrt(settings,360).mipmaps,true);
v('BLOOM',0);v('smart_ei',.4);assert.equal(planCrt(settings,360).average,false);assert.equal(planCrt(settings,360).edges,true);assert.equal(planCrt(settings,360).mipmaps,false);
v('TATE',1);assert.equal(planCrt(settings,360).average,false);
const roundtrip=new CrtGuestSettings({storage:null,loadStored:false,persistChanges:false});
assert.equal(roundtrip.applyPreset(settings.exportPreset()).ok,true);assert.deepEqual(roundtrip.exportPreset(),settings.exportPreset());
assert.equal(crtHalfFloat(.999755859375,'nearest'),1,'Half ties round to the even mantissa');
assert.equal(crtHalfFloat(.999755859375,'truncate'),.99951171875);
settings.applyStartupPreset();v('GAMMA_INPUT',1.1);
assert.equal(crtFrameMetadata(settings,1080,'truncate').inverseGamma,.90869140625);
assert.equal(crtFrameMetadata(settings,1080,null).inverseGamma,null,'Unknown device precision retains texture metadata');
v('GAMMA_INPUT',1);assert.equal(crtFrameMetadata(settings,1080,null).inverseGamma,1);
assert.equal(crtFrameMetadata(settings,1080,null).interlace,.25);
v('vga_mode',1);assert.equal(crtFrameMetadata(settings,1080,null).interlace,.75);
assert.equal(crtFrameMetadata(settings,240,null).interlace,.5);
settings.applyStartupPreset();v('GAMMA_INPUT',5);v('scangamma',.5);
assert.equal(optimizeNativeVertical('unchanged shader',settings,1080,1080),'unchanged shader','Low exponents need the original tiny-tail peak alpha');
console.log('PASS CRT dependency pruning, colour/temporal fusion guards, resolution-aware controls and legacy preset round trips.');
