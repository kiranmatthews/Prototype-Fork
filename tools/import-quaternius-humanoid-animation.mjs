#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { basename, resolve } from 'node:path';
import * as THREE from 'three';
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';

const TARGET_TO_PLAYER = Object.freeze({
  pelvis: 'hips',
  spine_01: 'torsoRoot',
  spine_02: 'spine',
  spine_03: 'chest',
  neck_01: 'neck',
  Head: 'head',
  clavicle_l: 'clavicleLeft',
  upperarm_l: 'shoulderLeft',
  lowerarm_l: 'elbowLeft',
  hand_l: 'wristLeft',
  clavicle_r: 'clavicleRight',
  upperarm_r: 'shoulderRight',
  lowerarm_r: 'elbowRight',
  hand_r: 'wristRight',
  thigh_l: 'hipLeft',
  calf_l: 'kneeLeft',
  foot_l: 'ankleLeft',
  ball_l: 'toeLeft',
  thigh_r: 'hipRight',
  calf_r: 'kneeRight',
  foot_r: 'ankleRight',
  ball_r: 'toeRight',
});

const PLAYER_HIERARCHY = Object.freeze([
  ['hips', null],
  ['torsoRoot', 'hips'],
  ['spine', 'torsoRoot'],
  ['chest', 'spine'],
  ['neck', 'chest'],
  ['head', 'neck'],
  ['clavicleLeft', 'chest'],
  ['shoulderLeft', 'clavicleLeft'],
  ['elbowLeft', 'shoulderLeft'],
  ['wristLeft', 'elbowLeft'],
  ['clavicleRight', 'chest'],
  ['shoulderRight', 'clavicleRight'],
  ['elbowRight', 'shoulderRight'],
  ['wristRight', 'elbowRight'],
  ['hipLeft', 'hips'],
  ['kneeLeft', 'hipLeft'],
  ['ankleLeft', 'kneeLeft'],
  ['toeLeft', 'ankleLeft'],
  ['hipRight', 'hips'],
  ['kneeRight', 'hipRight'],
  ['ankleRight', 'kneeRight'],
  ['toeRight', 'ankleRight'],
]);

const PLAYER_TO_TARGET = new Map(
  Object.entries(TARGET_TO_PLAYER).map(([target, player]) => [player, target]),
);

function parseArguments(argv) {
  const values = new Map();
  for (let index = 0; index < argv.length; index++) {
    const key = argv[index];
    if (!key.startsWith('--')) throw new Error(`unexpected positional argument: ${key}`);
    const value = argv[++index];
    if (!value || value.startsWith('--')) throw new Error(`missing value for ${key}`);
    values.set(key.slice(2), value);
  }
  const source = values.get('source');
  const clip = values.get('clip');
  const output = values.get('output');
  const symbol = values.get('symbol');
  if (!source || !clip || !output || !symbol) {
    throw new Error(
      'usage: node tools/import-quaternius-humanoid-animation.mjs ' +
      '--source <library.glb> --clip <clip-name> --output <module.ts> --symbol <PREFIX>',
    );
  }
  if (!/^[A-Z][A-Z0-9_]*$/.test(symbol)) {
    throw new Error('--symbol must be an uppercase TypeScript identifier');
  }
  return {
    source: resolve(source),
    clip,
    output: resolve(output),
    symbol,
  };
}

function finiteQuaternion(matrix) {
  const quaternion = new THREE.Quaternion().setFromRotationMatrix(
    new THREE.Matrix4().extractRotation(matrix),
  );
  if (quaternion.lengthSq() < 1e-12) return new THREE.Quaternion();
  return quaternion.normalize();
}

function playerCanonicalWorldQuaternions() {
  const result = new Map();
  for (const [joint, parent] of PLAYER_HIERARCHY) {
    const local = new THREE.Quaternion();
    if (joint === 'shoulderLeft') local.set(0, 0, Math.SQRT1_2, Math.SQRT1_2);
    if (joint === 'shoulderRight') local.set(0, 0, -Math.SQRT1_2, Math.SQRT1_2);
    const world = parent ? result.get(parent).clone().multiply(local) : local;
    result.set(joint, world.normalize());
  }
  return result;
}

function continuousQuaternion(previous, current) {
  if (previous && previous.dot(current) < 0) {
    current.set(-current.x, -current.y, -current.z, -current.w);
  }
  return current.normalize();
}

function rounded(value) {
  const finite = Number.isFinite(value) ? value : 0;
  const nearestInteger = Math.round(finite);
  const stable = Math.abs(finite - nearestInteger) < 1e-6 ? nearestInteger : finite;
  const result = Number(stable.toFixed(7));
  return Object.is(result, -0) ? 0 : result;
}

function tupleLine(time, values) {
  return `  [${rounded(time)}, [${values.map(rounded).join(', ')}]],`;
}

function moduleSource({
  symbol,
  sourceFile,
  sourceHash,
  clipName,
  duration,
  sampleRate,
  times,
  rootKeys,
  rotationKeys,
}) {
  const rotations = PLAYER_HIERARCHY.map(([joint]) => {
    const keys = rotationKeys.get(joint);
    return [
      `  ${joint}: [`,
      ...keys.map((quaternion, index) => tupleLine(times[index], quaternion.toArray())),
      '  ],',
    ].join('\n');
  }).join('\n');
  return `// Generated by tools/import-quaternius-humanoid-animation.mjs.
// Source motion is CC0. Do not hand-edit sampled values; edit them in Animation Studio.

export const ${symbol}_SOURCE = Object.freeze({
  author: 'Quaternius',
  pack: 'Universal Animation Library',
  edition: 'Standard',
  page: 'https://quaternius.com/packs/universalanimationlibrary.html',
  license: 'CC0-1.0',
  sourceFile: '${sourceFile}',
  sourceSha256: '${sourceHash}',
  sourceClip: '${clipName}',
  sourceRootMotion: false,
  sampleRate: ${rounded(sampleRate)},
  sourceFrameCount: ${times.length},
  conversion: 'Quaternius bind-world delta to player canonical-world/rest-local',
} as const);

export const ${symbol}_DURATION = ${rounded(duration)};

export const ${symbol}_ROOT_KEYS = [
${rootKeys.map((value, index) => tupleLine(times[index], value.toArray())).join('\n')}
] as const;

export const ${symbol}_ROTATION_KEYS = {
${rotations}
} as const;
`;
}

async function main() {
  const args = parseArguments(process.argv.slice(2));
  const bytes = await readFile(args.source);
  const arrayBuffer = bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength);
  const gltf = await new Promise((resolveGltf, reject) => {
    new GLTFLoader().parse(arrayBuffer, '', resolveGltf, reject);
  });
  const clip = gltf.animations.find((candidate) => candidate.name === args.clip);
  if (!clip) {
    throw new Error(
      `clip "${args.clip}" not found; available clips: ${gltf.animations.map(({ name }) => name).join(', ')}`,
    );
  }
  let skinnedMesh = null;
  gltf.scene.traverse((object) => {
    if (!skinnedMesh && object.isSkinnedMesh) skinnedMesh = object;
  });
  if (!skinnedMesh) throw new Error('source GLB has no SkinnedMesh skeleton');
  const targetBones = new Map(skinnedMesh.skeleton.bones.map((bone) => [bone.name, bone]));
  for (const target of Object.keys(TARGET_TO_PLAYER)) {
    if (!targetBones.has(target)) throw new Error(`source skeleton is missing ${target}`);
  }
  const referenceTrack = clip.tracks.find((track) => track.name === 'root.position');
  if (!referenceTrack || referenceTrack.times.length < 2) {
    throw new Error('clip must contain a sampled root.position track');
  }
  const times = Array.from(referenceTrack.times);
  for (const track of clip.tracks) {
    if (track.times.length !== times.length) {
      throw new Error(`track ${track.name} has ${track.times.length} keys; expected ${times.length}`);
    }
    for (let index = 0; index < times.length; index++) {
      if (Math.abs(track.times[index] - times[index]) > 1e-6) {
        throw new Error(`track ${track.name} does not share the clip sample clock`);
      }
    }
  }

  const targetRestWorld = new Map();
  for (let index = 0; index < skinnedMesh.skeleton.bones.length; index++) {
    const bone = skinnedMesh.skeleton.bones[index];
    targetRestWorld.set(bone.name, skinnedMesh.skeleton.boneInverses[index].clone().invert());
  }
  const targetPelvisRest = new THREE.Vector3().setFromMatrixPosition(
    targetRestWorld.get('pelvis'),
  );
  const sourceCanonicalWorld = playerCanonicalWorldQuaternions();
  const rotationKeys = new Map(PLAYER_HIERARCHY.map(([joint]) => [joint, []]));
  const previousQuaternions = new Map();
  const rootKeys = [];
  const mixer = new THREE.AnimationMixer(gltf.scene);
  mixer.clipAction(clip).reset().setLoop(THREE.LoopOnce, 0).play();
  const currentTarget = new THREE.Quaternion();
  const targetRest = new THREE.Quaternion();
  const parentDesiredWorld = new Map();

  for (const time of times) {
    mixer.setTime(Math.min(time, clip.duration));
    gltf.scene.updateMatrixWorld(true);
    const pelvisPosition = targetBones.get('pelvis').getWorldPosition(new THREE.Vector3());
    rootKeys.push(pelvisPosition.sub(targetPelvisRest));
    parentDesiredWorld.clear();
    for (const [joint, parent] of PLAYER_HIERARCHY) {
      const targetName = PLAYER_TO_TARGET.get(joint);
      const targetBone = targetBones.get(targetName);
      targetBone.getWorldQuaternion(currentTarget);
      targetRest.copy(finiteQuaternion(targetRestWorld.get(targetName)));
      const desiredWorld = currentTarget.clone()
        .multiply(targetRest.invert())
        .multiply(sourceCanonicalWorld.get(joint))
        .normalize();
      const desiredLocal = parent
        ? parentDesiredWorld.get(parent).clone().invert().multiply(desiredWorld)
        : desiredWorld.clone();
      continuousQuaternion(previousQuaternions.get(joint), desiredLocal);
      previousQuaternions.set(joint, desiredLocal.clone());
      rotationKeys.get(joint).push(desiredLocal);
      parentDesiredWorld.set(joint, desiredWorld);
    }
  }

  // The source is named as a loop; close its tiny exporter drift exactly so
  // browser playback cannot pop at the wrap boundary.
  rootKeys[rootKeys.length - 1].copy(rootKeys[0]);
  for (const keys of rotationKeys.values()) keys[keys.length - 1].copy(keys[0]);
  const interval = times.at(-1) / (times.length - 1);
  const output = moduleSource({
    symbol: args.symbol,
    sourceFile: basename(args.source),
    sourceHash: createHash('sha256').update(bytes).digest('hex'),
    clipName: clip.name,
    duration: clip.duration,
    sampleRate: 1 / interval,
    times,
    rootKeys,
    rotationKeys,
  });
  await writeFile(args.output, output, 'utf8');
  console.log(
    `Imported ${clip.name}: ${times.length} frames at ${(1 / interval).toFixed(3)} FPS, ` +
    `${rotationKeys.size} joints -> ${args.output}`,
  );
}

await main();
