import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import ts from 'typescript';
const memory=new Map();
globalThis.localStorage={getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,String(v)),removeItem:k=>memory.delete(k)};
const source=await readFile(new URL('../src/campaign.ts',import.meta.url),'utf8');
const code=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.ES2020}}).outputText;
const c=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const definition=c.campaignLevelByKey('quagmire-race');
assert.equal(definition.levelId,'spaghetti-rails');assert.equal(definition.name,'Spaghetti Rails');
assert.equal(definition.islandId,'island-5');assert.equal(!!definition.placeholder,false);
assert.equal(definition.skateRace,true);assert.equal(definition.gemReward,'win');
assert.deepEqual(c.validateCampaignMapGraph(),[]);
const store=new c.CampaignStore();store.startEphemeral({unlockAll:true});
assert.equal(store.levelPlayable('spaghetti-rails'),true);assert.equal(store.runModesUnlocked('spaghetti-rails'),false);
store.newGame(1); // The fixture storage is an isolated in-memory map.
store.commitRaceResult('spaghetti-rails',{won:false,boxGem:true});
assert.equal(store.levelProgress('spaghetti-rails').boxGem,false);assert.equal(store.runModesUnlocked('spaghetti-rails'),false);
store.commitRaceResult('spaghetti-rails',{won:true,boxGem:false});
const won=store.levelProgress('spaghetti-rails');
assert.equal(won.raceWon,true);assert.equal(won.crystal,true);assert.equal(won.boxGem,true);
assert.equal(store.runModesUnlocked('spaghetti-rails'),true);
assert.equal(definition.progressKey,'quagmire-race');
assert.deepEqual(store.active.levels['quagmire-race'],won,'The original campaign slot remains the save identity');
store.commitTimeTrial('spaghetti-rails',{time:110,medal:'gold'});
store.saveActive();const reloaded=new c.CampaignStore();reloaded.load(1);
assert.equal(reloaded.levelProgress('spaghetti-rails').bestTime,110);
assert.equal(reloaded.levelProgress('spaghetti-rails').timeMedal,'gold');
assert.equal(reloaded.active.levels['quagmire-race'].raceWon,true);
console.log('PASS Spaghetti Rails occupies Quagmire Caverns, keeps the stable save slot, awards wins only and unlocks persistent time-trial medals');
