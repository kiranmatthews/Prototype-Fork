"""Write measured, uniformly-scaled registry entries for the modular kit."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[2]
names={'baybody':'stucco-body','baytrim':'stucco-trim','bayroof':'tile-roof','baywindow':'shutter-window','baydoor':'arched-door','bayawning':'striped-awning',
 'baybalcony':'balcony','baycorner':'corner-quoins','baydisplay':'display-window','baytrunk':'palm-trunk',
 'baycrown':'palm-crown','baypot':'flower-pot','baybox':'flower-box','bayvine':'flower-vine',
 'baylamp':'lantern','baypost':'rail-post','baylantern':'lighthouse-lantern','bayrock':'sandstone'}
heights={'arched-door':3.4,'palm-trunk':8,'lantern':4.8,'rail-post':1.25,'corner-quoins':7.6,'flower-vine':4.2}
lines=['// Generated by tools/coastal-town-assets/registry.py from measured Meshy geometry.',
 "import type { JungleAssetSpec } from './jungleAssets';",'export const COASTAL_TOWN_ASSETS = {']
for alias,name in names.items():
 m=json.loads((ROOT/'public/coastal-town'/f'{name}.json').read_text());s=m['sizeAtDefaultWidth']
 if name in heights:s=[round(x*heights[name]/s[1],5) for x in s]
 lines.append(f'  {alias}: '+json.dumps({'file':'../coastal-town/'+name,'label':'Coastal / '+name.replace('-',' '),'size':s,
  'wind':name=='palm-crown','lod':True,'distanceLod':True,'cellSize':40,'lodRange':[56,90],'doubleSided':name in ['palm-crown','flower-vine'],'normalStrength':0})+',')
for alias,name in [('baytownmatte','town-matte-alpha'),('bayheadlandmatte','headland-matte-alpha')]:
 lines.append(f'  {alias}: '+json.dumps({'file':'','image':'coastal-town/'+name+'.webp','label':'Coastal / '+name,'size':[210,70,.02],'wind':False,'matte':True,'alphaCutout':True})+',')
lines.append('} as const satisfies Record<string, JungleAssetSpec>;')
lines.append('export type CoastalTownAssetKind = keyof typeof COASTAL_TOWN_ASSETS;')
(ROOT/'src/coastalTownAssets.ts').write_text('\n'.join(lines)+'\n')
print('Wrote 16 Meshy components, two code-authored structural primitives and two mattes')
