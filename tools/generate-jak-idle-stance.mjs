// Writes src/animation/jakIdleStance.generated.ts: the EA Skate study's off-board
// stand, retargeted onto the player rig exactly as the skate study shows it,
// as the joint rotations an animation clip stores (each relative to its rest).
//   node tools/generate-jak-idle-stance.mjs
// It is the pose the study's standing dismount ends on, so D's idle and that
// dismount meet in the same stance.
import {readFile,writeFile} from 'node:fs/promises';
import {gunzipSync} from 'node:zlib';
import {withSkateRuntime} from './jungle-cup-harness.mjs';

const SOURCE='BR_DISMOUNT_LO_INTO_STAND_0';
const data=JSON.parse(gunzipSync(await readFile(new URL('../public/motion-study/skate/motion.json.gz',import.meta.url))));
await withSkateRuntime(async({server,scene,Player,THREE})=>{
  const {SkateRetargeter,BONE_MAP}=await server.ssrLoadModule('/src/skateReferenceLab/retarget.ts');
  const clip=data.clips.find(c=>c.name===SOURCE);
  if(!clip)throw new Error(`The skate study has no ${SOURCE}.`);
  const p=new Player(scene),rig=p.enterAnimationPreview();
  p.applyAnimationDeformations({});p.syncCharacterAppearance({upperArmRestAngleWeight:0});
  const leg=rig.jointsById.get('kneeLeft').node.position.length()+rig.jointsById.get('ankleLeft').node.position.length();
  // Mirrored, as the playable study plays its regular stance.
  const retarget=new SkateRetargeter(rig,data,leg,{mirror:true}),frame=clip.frames.length-1;
  retarget.apply(clip,frame/clip.fps,{travel:false,rest:false});
  const lines=BONE_MAP.map(([,id])=>{
    const joint=rig.jointsById.get(id);
    const q=new THREE.Quaternion().fromArray(joint.rest.quaternion).invert().multiply(joint.node.quaternion).normalize();
    if(q.w<0)q.set(-q.x,-q.y,-q.z,-q.w);
    return `  ${id}:[${q.toArray().map(x=>+x.toFixed(6)).join(',')}],`;
  });
  await writeFile(new URL('../src/animation/jakIdleStance.generated.ts',import.meta.url),
`// Generated by tools/generate-jak-idle-stance.mjs. Do not edit by hand.
// The EA Skate study's off-board stand (${SOURCE}, frame ${frame} of ${clip.frames.length}),
// retargeted onto the player rig as the playable study shows it. Each entry is
// a joint's rotation relative to its rest, as an animation clip stores it.
import type {QuaternionTuple} from './types';

export const JAK_IDLE_STANCE_SOURCE='${SOURCE}';
export const JAK_IDLE_STANCE:Readonly<Record<string,QuaternionTuple>>={
${lines.join('\n')}
};
`);
  console.log(`wrote ${lines.length} joints from ${SOURCE} frame ${frame}`);
});
