awake.sync(true);awake.sync(false);awake.sync(true);
const superseded=lock();pending.shift().resolve(superseded);await flush();assert.equal(superseded.releases,1);assert.equal(pending.length,1,'active latest state loses its replacement request');
const current=lock();pending.shift().resolve(current);await flush();assert.equal(awake.diagnostics.held,true);
await current.release();assert.equal(awake.diagnostics.held,false);
for(let i=0;i<1000;i++)awake.sync(true);assert.equal(pending.length,0,'OS revocation causes retry thrash');
awake.activate(true);assert.equal(pending.length,1,'fresh gesture cannot retry revoked lock');
